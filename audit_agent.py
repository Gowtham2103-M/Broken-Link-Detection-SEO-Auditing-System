DEFAULT_RULE = {
    "what": lambda i: f"The crawler recorded '{i['issue_type']}' for {i['target_url']}.",
    "cause": "The finding did not match a known rule, so the cause is unknown.",
    "impact": "The detected issue may affect website quality.",
    "action": "Inspect the page and verify the finding before making changes.",
    "example": "Review the relevant URL and its server response.",
}


def _resolve(value, issue):
    return value(issue) if callable(value) else value


def analyze_issue(issue):
    """Explain one issue. ``issue`` may be a raw database row or an effective issue."""
    issue = effective_issue(issue)
    rule = RULES.get(issue["issue_type"], DEFAULT_RULE)
    rank = priority_key(issue)[0]

    stored_detail = (issue.get("detail") or "").strip()

    return {
        "issue_id": issue.get("issue_id"),
        "issue_type": issue["issue_type"],
        "source_url": issue.get("source_url"),
        "target_url": issue.get("target_url"),
        "http_status": issue.get("http_status"),
        "status": issue.get("status"),
        "severity": issue["severity"],
        "severity_label": SEVERITY_LABEL[issue["severity"]],
        "category": issue["category"],
        "category_label": issue["category_label"],
        "priority": rank + 1,
        "priority_label": PRIORITY_LABEL.get(rank, "Low"),
        "explanation": _resolve(rule["what"], issue),
        "cause": _resolve(rule["cause"], issue),
        "impact": _resolve(rule["impact"], issue),
        "recommended_action": _resolve(rule["action"], issue),
        "example_fix": _resolve(rule["example"], issue),
        "crawler_detail": stored_detail,
    }


def get_audit_recommendations(scan_id):
    from database import get_connection

    connection = None
    cursor = None

    try:
        connection = get_connection()
        cursor = connection.cursor(dictionary=True)

        cursor.execute(
            """
            SELECT issue_id, issue_type, source_url, target_url,
                   http_status, severity, status, category, detail
            FROM issues
            WHERE scan_id = %s
            """,
            (scan_id,),
        )

        analyses = [
            (effective_issue(row), analyze_issue(row))
            for row in cursor.fetchall()
        ]

        # Open issues first, then by severity/category priority.
        analyses.sort(
            key=lambda pair: (
                str(pair[0].get("status")).lower() == "resolved",
                priority_key(pair[0]),
            )
        )

        return [analysis for _, analysis in analyses]

    finally:
        if cursor:
            cursor.close()
        if connection and connection.is_connected():
            connection.close()


if __name__ == "__main__":
    try:
        scan_id = int(input("Enter scan ID to analyze: "))
        results = get_audit_recommendations(scan_id)

        if not results:
            print("No issues found for this scan.")

        for item in results:
            print("\n" + "=" * 50)
            print(f"Issue #{item['issue_id']}: {item['issue_type']}")
            print(f"Priority: {item['priority_label']}  Severity: {item['severity_label']}")
            print(f"Status: {item['status']}")
            print(f"Target: {item['target_url']}")
            print(f"HTTP status: {item['http_status']}")
            print(f"What happened: {item['explanation']}")
            print(f"Likely cause: {item['cause']}")
            print(f"Impact: {item['impact']}")
            print(f"Recommended action: {item['recommended_action']}")
            print(f"Example fix: {item['example_fix']}")

    except ValueError:
        print("Please enter a valid numeric scan ID.")
    except Exception as error:
        print("Audit analysis failed:", error)
